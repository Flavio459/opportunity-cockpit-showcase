// Helper functions for state machine and calculations
function getScenario(scenarioId, lang = "en") {
  const sc = SCENARIOS[scenarioId];
  if (!sc) return null;
  return sc[lang] || sc["en"];
}

function calculateSavings(baseHours, bonusHours, hourlyRate = 39.0) {
  const totalHours = Number((baseHours + bonusHours).toFixed(1));
  const totalValue = Number((totalHours * hourlyRate).toFixed(2));
  return { totalHours, totalValue };
}

function validateDictionaries() {
  const langs = ["en", "ar", "pt"];
  const enKeys = Object.keys(UI_TRANSLATIONS.en);
  for (const l of langs) {
    if (!UI_TRANSLATIONS[l]) return false;
    for (const k of enKeys) {
      if (typeof UI_TRANSLATIONS[l][k] === "undefined") {
        return false;
      }
    }
  }
  return true;
}

function getScenarioAudioPath(scenarioId, lang = "en") {
  const validScenarios = ["audio_memo", "proposal_request", "board_digest"];
  const validLangs = ["en", "ar", "pt"];
  const s = validScenarios.includes(scenarioId) ? scenarioId : "audio_memo";
  const l = validLangs.includes(lang) ? lang : "en";
  return `assets/audio/scenario_${s}_${l}.mp3`;
}

